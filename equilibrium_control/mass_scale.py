#!/usr/bin/env python3
"""Radial tracer surface-density and exponential scale-length evolution.

These 3000 massless-tracer runs have a FIXED analytic potential: the plot is
not evidence for self-consistent mass transport or spontaneous bar formation.

Input: evolution.npz generated by equilibrium_control/control.py
Output: mass_scale_evolution.png, mass_scale_evolution.csv
"""
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parent
CASES = ("unforced", "forced")
LENGTH_KPC_PER_CODE = 15.0
BIN_EDGES_KPC = np.linspace(0.5, 12.5, 25)
FIT_RANGE_KPC = (1.5, 9.0)
WINDOW = 21  # 21 saved 5 Myr epochs = 105 Myr running mean
EPOCH_INDICES = (0, 450, 900)

def surface_density(positions):
    radii = np.hypot(positions[:, 0], positions[:, 1]) * LENGTH_KPC_PER_CODE
    counts, _ = np.histogram(radii, bins=BIN_EDGES_KPC)
    annuli = np.pi * (BIN_EDGES_KPC[1:] ** 2 - BIN_EDGES_KPC[:-1] ** 2)
    centres = 0.5 * (BIN_EDGES_KPC[1:] + BIN_EDGES_KPC[:-1])
    # Equal-weight massless tracers: this is a number-density PROXY only.
    return centres, counts / annuli

def disc_scale_length(positions):
    r, sigma = surface_density(positions)
    valid = (sigma > 0) & (r >= FIT_RANGE_KPC[0]) & (r <= FIT_RANGE_KPC[1])
    if valid.sum() < 3:
        raise ValueError("Insufficient populated radial annuli for exponential fit")
    slope, intercept = np.polyfit(r[valid], np.log(sigma[valid]), deg=1)
    if slope >= 0:
        raise ValueError("Nondecreasing tracer profile: positive scale length undefined")
    return -1.0 / slope

def running_mean(arr):
    n = WINDOW // 2
    return np.convolve(np.pad(arr, (n, n), mode="edge"),
                       np.ones(WINDOW) / WINDOW, mode="valid")

def main():
    sets = {}
    for case in CASES:
        path = ROOT / "results" / case / "evolution.npz"
        with np.load(path) as data:
            positions = data["x"]
            time = data["history"][:, 0]
        if len(time) != len(positions):
            raise ValueError("Snapshot/time mismatch")
        raw_rd = np.array([disc_scale_length(snap) for snap in positions])
        sets[case] = dict(x=positions, time=time, raw_rd=raw_rd,
                          rd=running_mean(raw_rd))
        print(f"{case}: R_d raw t=0={raw_rd[0]:.3f} kpc, "
              f"t=4500={raw_rd[-1]:.3f} kpc")

    # CSV includes unsmoothed values, so the running mean does not conceal
    # any orbit-induced oscillations or change of the chosen fit range.
    u, f = sets["unforced"], sets["forced"]
    if not np.array_equal(u["time"], f["time"]):
        raise ValueError("Runs must share an identical time axis")
    np.savetxt(ROOT / "mass_scale_evolution.csv",
               np.column_stack([u["time"], u["raw_rd"], f["raw_rd"],
                                u["rd"], f["rd"]]), delimiter=",", fmt="%.8f",
               header="time_Myr,Rd_unforced_kpc,Rd_forced_kpc,Rd_unforced_105Myr_mean_kpc,Rd_forced_105Myr_mean_kpc",
               comments="")

    plt.rcParams.update({"font.size": 10, "axes.linewidth": 1,
                         "xtick.direction": "in", "ytick.direction": "in"})
    fig, axes = plt.subplots(2, 1, figsize=(8.2, 8.8), layout="constrained")
    labels = {"unforced": "Unforced fixed-potential control",
              "forced": "Externally imposed rotating m=2 control"}
    for case, ls in (("unforced", "-"), ("forced", "--")):
        axes[0].plot(sets[case]["time"], sets[case]["rd"], ls,
                     lw=2.0, label=labels[case])
    axes[0].set(xlabel="Time [Myr]",
                ylabel=r"Fitted exponential scale length $R_d$ [kpc]",
                title="Disc scale-length evolution (105 Myr running mean)")
    axes[0].legend(fontsize=8)
    axes[0].grid(alpha=0.25)

    times = {0: "0 Myr", 450: "2250 Myr", 900: "4500 Myr"}
    styles = {0: "-", 450: "--", 900: ":"}
    for case, marker, prefix in (("unforced", "o", "Unforced"),
                                  ("forced", "s", "Forced")):
        for index in EPOCH_INDICES:
            if index >= len(sets[case]["x"]):
                raise ValueError(f"Snapshot index {index} missing")
            r, sigma = surface_density(sets[case]["x"][index])
            axes[1].plot(r, sigma, linestyle=styles[index], marker=marker,
                         markersize=3, lw=1.2, label=f"{prefix}, {times[index]}")
    axes[1].set(xlabel="Radius [kpc]",
                ylabel=r"Tracer surface density [counts kpc$^{-2}$]",
                title="Radial mass-distribution proxy at 0, 2.25 and 4.5 Gyr",
                yscale="log")
    axes[1].legend(fontsize=7, ncol=2)
    axes[1].grid(alpha=0.25)
    fig.suptitle("Earlier 3,000-tracer fixed-potential controls", fontsize=12)
    fig.savefig(ROOT / "mass_scale_evolution.png", dpi=170)
    plt.close(fig)
    print("Saved mass_scale_evolution.png and mass_scale_evolution.csv")

if __name__ == "__main__":
    main()
